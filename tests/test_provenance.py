import json
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
METRICS = os.path.join(ROOT, "figures", "metrics.json")
README = os.path.join(ROOT, "README.md")
RECONCILER = os.path.join(ROOT, "tools", "reconcile_readme.py")


def count_numbers(obj):
    """Count numeric leaves anywhere in a JSON structure."""
    if isinstance(obj, dict):
        return sum(count_numbers(v) for v in obj.values())
    if isinstance(obj, list):
        return sum(count_numbers(v) for v in obj)
    if isinstance(obj, bool):
        return 0
    if isinstance(obj, (int, float)):
        return 1
    return 0


def readme_table():
    """Extract the published results table from README.md as a list of rows."""
    with open(README) as handle:
        lines = handle.read().splitlines()

    rows, in_table = [], False
    for line in lines:
        if line.startswith("| Method |") and "Bit Acc" in line:
            in_table = True
            continue
        if in_table:
            if not line.startswith("|"):
                break
            if re.match(r"^\|[\s:\-|]+\|$", line):
                continue
            cells = [c.strip() for c in line.strip("|").split("|")]
            rows.append(cells)
    return rows


def published_numbers():
    """Every numeric token appearing in the published table."""
    values = []
    for row in readme_table():
        for cell in row[3:]:  # skip method, domain, PSNR-adjacent labels
            try:
                values.append((row[0], float(cell)))
            except ValueError:
                values.append((row[0], cell))  # non-numeric, e.g. a range
    return values


def main():
    failures = []
    print("=" * 78)
    print("PROVENANCE FALSIFIER — row 6b")
    print("property: every published value derives from a committed numeric artifact")
    print("=" * 78)

    # --- F1: the artifact must contain numbers --------------------------------
    if not os.path.exists(METRICS):
        print("  [FAIL] F1 metrics.json exists")
        failures.append("F1-missing")
    else:
        with open(METRICS) as handle:
            metrics = json.load(handle)
        n = count_numbers(metrics)
        if n == 0:
            print(f"  [FAIL] F1 metrics.json contains numeric values: found {n}")
            failures.append("F1-no-numbers")
        else:
            print(f"  [PASS] F1 metrics.json contains {n} numeric values")

    # --- F2: every published value must be derivable --------------------------
    derived = False
    if os.path.exists(RECONCILER):
        print("  [PASS] F2a reconciliation script present")
        derived = True
    else:
        print("  [FAIL] F2a reconciliation script present: tools/reconcile_readme.py absent")
        failures.append("F2-no-reconciler")

    if derived:
        sys.path.insert(0, os.path.join(ROOT, "tools"))
        import reconcile_readme  # noqa: E402

        expected = reconcile_readme.table_markdown(
            json.load(open(METRICS))
        )
        with open(README) as handle:
            body = handle.read()
        if expected.strip() not in body:
            print("  [FAIL] F2b published table equals the generated table")
            failures.append("F2-table-mismatch")
        else:
            print("  [PASS] F2b published table equals the generated table")
    else:
        print("  [FAIL] F2b published table is generated from the artifact: no chain exists")
        failures.append("F2-no-chain")

    # --- F3: a hand-edit must be detected -------------------------------------
    if derived:
        with open(README) as handle:
            original = handle.read()
        try:
            with open(METRICS) as handle:
                metrics = json.load(handle)
            expected = reconcile_readme.table_markdown(metrics)
            tampered = original.replace("| 0.50 |", "| 0.99 |", 1)
            if tampered == original:
                tampered = original + "\n<!-- hand-edit -->\n"
            detected = expected.strip() not in tampered
            if detected:
                print("  [PASS] F3 a hand-edited published value is detected")
            else:
                print("  [FAIL] F3 a hand-edited published value is detected")
                failures.append("F3-hand-edit-undetected")
        finally:
            with open(README, "w") as handle:
                handle.write(original)
    else:
        print("  [FAIL] F3 a hand-edited published value is detected: nothing to compare against")
        failures.append("F3-no-mechanism")

    print("-" * 78)
    if failures:
        print(f"FAILED: {len(failures)} assertion(s) — {', '.join(failures)}")
        return 1
    print("PASSED: all provenance assertions hold")
    return 0


if __name__ == "__main__":
    sys.exit(main())
